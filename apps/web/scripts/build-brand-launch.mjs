/** Platform launch exports; called by brand:motion. No Android SDK or installed fonts needed to generate. */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { Resvg } from "@resvg/resvg-js";
import {
  BRAND_INK,
  BRAND_LIME,
  LOGO_HEIGHT,
  LOGO_WIDTH,
  MARK_PATHS,
  WORDMARK_PATH,
} from "../src/lib/brand.ts";

const web = resolve(import.meta.dirname, "..");
// The public web export has no sibling Android app: keep handoff files inside its own tree instead.
const android = existsSync(resolve(web, "../tv-android/app/build.gradle.kts"))
  ? resolve(web, "../tv-android/app/src/main/res")
  : resolve(web, "brand/motion/android/res");
const document = (width, height, body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">${body}</svg>`;
const mark = MARK_PATHS.map((d) => `<path d="${d}"/>`).join("");
const logo = `<g transform="scale(.875)" fill="${BRAND_LIME}">${mark}</g><path fill="#f5f6f8" d="${WORDMARK_PATH}"/>`;
const png = (source) => new Resvg(source, { font: { loadSystemFonts: false } }).render().asPng();
function write(path, data) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, data);
}

export function buildLaunchAssets() {
  const { devices } = JSON.parse(readFileSync(resolve(web, "brand/motion/apple-devices.json"), "utf8"));
  const entries = [];
  for (const device of devices) {
    for (const orientation of ["portrait", "landscape"]) {
      const landscape = orientation === "landscape";
      const width = (landscape ? device.height : device.width) * device.scale;
      const height = (landscape ? device.width : device.height) * device.scale;
      const logoWidth = Math.round(Math.min((width / device.scale) * 0.64, 480) * device.scale);
      const scale = logoWidth / LOGO_WIDTH;
      const svg = document(
        width,
        height,
        `<rect width="${width}" height="${height}" fill="${BRAND_INK}"/><g transform="translate(${(width - logoWidth) / 2} ${(height - LOGO_HEIGHT * scale) / 2}) scale(${scale})">${logo}</g>`,
      );
      const url = `/brand/motion/apple/startup-${width}x${height}.png`;
      write(resolve(web, `public${url}`), png(svg));
      entries.push({
        url,
        media: `screen and (device-width: ${device.width}px) and (device-height: ${device.height}px) and (-webkit-device-pixel-ratio: ${device.scale}) and (orientation: ${orientation})`,
      });
    }
  }
  write(
    resolve(web, "src/lib/brand-startup.gen.ts"),
    `// Generated by brand:motion from brand/motion/apple-devices.json. Server metadata only.\nexport const APPLE_STARTUP_IMAGES = ${JSON.stringify(entries, null, 2)};\n`,
  );
  write(
    resolve(web, "brand/motion/apple-startup-links.html"),
    `${entries.map((e) => `<link rel="apple-touch-startup-image" href="${e.url}" media="${e.media}" />`).join("\n")}\n`,
  );
  write(
    resolve(web, "public/brand/motion/apple/catalog.json"),
    `${JSON.stringify({ devices, images: entries }, null, 2)}\n`,
  );

  // AVD area 432, central safe area 288; when the system draws it in its 288 dp icon, the mark is 128 dp.
  write(
    resolve(android, "drawable/lumovio_splash_mark.xml"),
    `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by brand:motion from brand.ts. Same final geometry as intro-compact. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="432dp" android:height="432dp" android:viewportWidth="432" android:viewportHeight="432">
  <group android:translateX="120" android:translateY="120" android:scaleX="1.5" android:scaleY="1.5">
    <group android:name="projector" android:pivotX="18" android:pivotY="64">
      <path android:name="projector_fill" android:fillColor="@color/lime" android:pathData="${MARK_PATHS[0]}"/>
    </group>
    <group android:name="screen" android:pivotX="38" android:pivotY="64">
      <path android:name="screen_fill" android:fillColor="@color/lime" android:pathData="${MARK_PATHS[1]}"/>
    </group>
  </group>
</vector>\n`,
  );
  const animator = (body) =>
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by brand:motion. -->\n${body}\n`;
  for (const [name, property, from, delay, duration] of [
    ["projector_alpha", "fillAlpha", 0, 0, 342],
    ["projector_scale", "scaleY", 0.8, 0, 342],
    ["screen_scale", "scaleX", 0.04, 108, 630],
    ["screen_alpha", "fillAlpha", 0, 108, 792],
  ]) {
    write(
      resolve(android, `animator/lumovio_${name}.xml`),
      animator(
        `<objectAnimator xmlns:android="http://schemas.android.com/apk/res/android" android:propertyName="${property}" android:valueFrom="${from}" android:valueTo="1" android:valueType="floatType" android:startOffset="${delay}" android:duration="${duration}" android:interpolator="@android:interpolator/fast_out_slow_in"/>`,
      ),
    );
  }
  write(
    resolve(android, "drawable/lumovio_splash.xml"),
    animator(`<animated-vector xmlns:android="http://schemas.android.com/apk/res/android" android:drawable="@drawable/lumovio_splash_mark">
  <target android:name="projector_fill" android:animation="@animator/lumovio_projector_alpha"/>
  <target android:name="projector" android:animation="@animator/lumovio_projector_scale"/>
  <target android:name="screen" android:animation="@animator/lumovio_screen_scale"/>
  <target android:name="screen_fill" android:animation="@animator/lumovio_screen_alpha"/>
</animated-vector>`),
  );
  for (const [density, factor] of [
    ["mdpi", 1],
    ["hdpi", 1.5],
    ["xhdpi", 2],
    ["xxhdpi", 3],
    ["xxxhdpi", 4],
  ]) {
    const size = 128 * factor;
    write(
      resolve(android, `drawable-${density}/lumovio_splash_still.png`),
      png(document(size, size, `<g transform="scale(${factor})" fill="${BRAND_LIME}">${mark}</g>`)),
    );
  }
  write(
    resolve(android, "drawable/lumovio_launch_background.xml"),
    animator(`<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
  <item android:drawable="@color/ink"/>
  <item><bitmap android:gravity="center" android:src="@drawable/lumovio_splash_still"/></item>
</layer-list>`),
  );
  // A lightweight, vector-only preview of the identical centred PNG layout, not a fake OS screenshot.
  const preview = (width, height) => {
    const logoWidth = Math.min(width * 0.64, 480);
    const scale = logoWidth / LOGO_WIDTH;
    return document(
      width,
      height,
      `<rect width="${width}" height="${height}" fill="${BRAND_INK}"/><g transform="translate(${(width - logoWidth) / 2} ${(height - LOGO_HEIGHT * scale) / 2}) scale(${scale})">${logo}</g>`,
    );
  };
  console.log(`Built ${entries.length} Apple startup PNGs, metadata and Android AVD + five density PNGs.`);
  return { iphone: preview(390, 844), ipad: preview(820, 1180) };
}
